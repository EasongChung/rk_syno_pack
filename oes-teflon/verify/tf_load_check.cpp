/* libteflon.so 导出的 external delegate 入口（Mesa teflon，旧式 C ABI）
 *
 * 用 dlopen/dlsym 而**不做链接期依赖**，理由：
 *   - 设备上 libteflon.so 与 libdrm.so.2 必须同目录（DSM 系统完全没有 libdrm），
 *     链接期依赖会额外引入 RPATH/LD_LIBRARY_PATH 的部署复杂度
 *   - dlopen 的路径可在运行时指定，与已验证可行的 teflon_dlopen 机制一致
 *   - delegate 符号只在运行时解析，链接期不需要 libteflon.so 存在
 */
typedef TfLiteDelegate* (*DelegateCreateFn)(const char*);
typedef void (*DelegateDestroyFn)(TfLiteDelegate*);

static void* g_handle = nullptr;
static DelegateDestroyFn g_destroy = nullptr;

/* teflon 内部的 tflite_type_name 是 file-static 短名版本（L1370），
 * 与公开枚举名不同。这里用公开枚举打印，便于阅读。 */
static const char* dtype_name(TfLiteType t) {
  /* ⚠️ 本表**必须与 TFLite 2.13 的 TfLiteType 枚举逐项一致**，不要凭印象加。
   * 权威来源：tensorflow/lite/core/c/c_api_types.h（v2.13.0，实测 19 个成员）：
   *   kTfLiteNoType kTfLiteFloat32 kTfLiteInt32 kTfLiteUInt8 kTfLiteInt64
   *   kTfLiteString kTfLiteBool kTfLiteInt16 kTfLiteComplex64 kTfLiteInt8
   *   kTfLiteFloat16 kTfLiteFloat64 kTfLiteComplex128 kTfLiteUInt64
   *   kTfLiteResource kTfLiteVariant kTfLiteUInt32 kTfLiteUInt16 kTfLiteInt4
   *
   * 注意：kTfLiteBFloat16 / kTfLiteUInt4 在 **2.13 中不存在**，
   *       写了会编译失败（已实测）。新增成员前必须先查那个头文件。
   *
   * 为什么必须列全：teflon 的 create_resource() 对这些类型的处理**不同**——
   *   - Int8/UInt8/Int16/UInt16/Float16 → bytes 1/2
   *   - Int32/UInt32/Float32          → bytes 4
   *   - Int64/UInt64/Float64/Complex64→ bytes 8
   *   - String/Bool/Complex128/Resource/Variant/Int4 → **落进
   *     default: unreachable("Unsupported TF type")**
   * 若在驱动里把它们混成 "OTHER"，就无法判断崩因是不是这个 default 分支。 */
  switch (t) {
    case kTfLiteNoType:     return "NoType";     /* fill_tensor 会直接 return */
    case kTfLiteFloat32:    return "Float32";
    case kTfLiteInt32:      return "Int32";
    case kTfLiteUInt8:      return "UInt8";
    case kTfLiteInt64:      return "Int64";
    case kTfLiteString:     return "String";     /* create_resource 不支持 */
    case kTfLiteBool:       return "Bool";       /* create_resource 不支持 */
    case kTfLiteInt16:      return "Int16";
    case kTfLiteComplex64:  return "Complex64";
    case kTfLiteInt8:       return "Int8";
    case kTfLiteFloat16:    return "Float16";
    case kTfLiteFloat64:    return "Float64";
    case kTfLiteComplex128: return "Complex128"; /* create_resource 不支持 */
    case kTfLiteUInt64:     return "UInt64";
    case kTfLiteResource:   return "Resource";   /* create_resource 不支持 */
    case kTfLiteVariant:    return "Variant";    /* create_resource 不支持 */
    case kTfLiteUInt32:     return "UInt32";
    case kTfLiteUInt16:     return "UInt16";
    case kTfLiteInt4:       return "Int4";       /* create_resource 不支持 */
    default:                return "UNKNOWN";    /* 出现即说明枚举表与头文件已不同步 */
  }
}

/* ---- 崩溃处理器：段错误时把调用栈写到 stderr（无缓冲，已保证不丢）---- */
static void crash_handler(int sig) {
  void* bt[64];
  const int n = backtrace(bt, 64);
  const char* name = (sig == SIGSEGV) ? "SIGSEGV"
                  : (sig == SIGBUS)  ? "SIGBUS"
                                     : "SIGABRT";
  std::fprintf(stderr, "\n*** %s ***\n", name);
  std::fprintf(stderr, "*** backtrace (%d frames) ***\n", n);
  backtrace_symbols_fd(bt, n, STDERR_FILENO);
  std::fprintf(stderr,
               "*** 提示：地址用 addr2line -f -C -e <elf> <addr> 解析；\n"
               "*** libteflon.so 的偏移可用 nm -D + objdump -d 反查。\n");
  _exit(139);
}

static void install_crash_handler() {
  struct sigaction sa;
  std::memset(&sa, 0, sizeof(sa));
  sa.sa_handler = crash_handler;
  sa.sa_flags = SA_NODEFER;   /* 崩在 handler 里也能再崩一次 */
  sigaction(SIGSEGV, &sa, nullptr);
  sigaction(SIGBUS,  &sa, nullptr);
  sigaction(SIGABRT, &sa, nullptr);
}

/* ---- 真实推理 + 计时 + 输出校验 ----
 *
 * 独立成函数而非内联：用提前 return 代替 goto。
 * 本机无 C++ 前端（无 cc1plus），goto 跨嵌套作用域**无法本地验证**，
 * 而这是一个可靠的等价写法（提前 return 在 C++ 里语义明确）。
 *
 * 预热 3 次：首次 Invoke 会包含惰性初始化（NPU 资源分配、shader 编译等），
 * 计入计时会严重低估稳态性能。
 *
 * 报 min / 中位数 / 均值三个数：只报均值会被单次抖动带偏；
 * min 最接近"稳态性能上限"，中位数抗离群。 */
static void run_invoke(tflite::Interpreter* interpreter, int invoke_n) {
  const std::vector<int>& ins = interpreter->inputs();
  const std::vector<int>& outs = interpreter->outputs();
  if (ins.empty() || outs.empty()) {
    std::fprintf(stderr, "INVOKE 跳过: 输入或输出张量为空\n");
    return;
  }
  TfLiteTensor* in = interpreter->tensor(ins[0]);
  if (in == nullptr || in->data.raw == nullptr || in->bytes == 0) {
    std::fprintf(stderr, "INVOKE 跳过: 输入张量不可写\n");
    return;
  }

  /* 确定性填充：两组必须完全一致，否则对比无意义 */
  {
    std::uint8_t* p = static_cast<std::uint8_t*>(in->data.raw);
    for (std::size_t k = 0; k < in->bytes; k++)
      p[k] = static_cast<std::uint8_t>((k * 31u + 7u) & 0xFFu);
  }
  std::fprintf(stderr, "INVOKE 输入填充: bytes=%zu pattern=(i*31+7)&0xFF\n",
               in->bytes);

  const int warmup = 3;
  for (int w = 0; w < warmup; w++) {
    if (interpreter->Invoke() != kTfLiteOk) {
      std::fprintf(stderr, "INVOKE 预热第 %d 次失败\n", w + 1);
      return;
    }
  }

  std::vector<double> ms;
  ms.reserve(static_cast<std::size_t>(invoke_n));
  for (int r = 0; r < invoke_n; r++) {
    struct timespec t0, t1;
    clock_gettime(CLOCK_MONOTONIC, &t0);
    const TfLiteStatus st = interpreter->Invoke();
    clock_gettime(CLOCK_MONOTONIC, &t1);
    if (st != kTfLiteOk) {
      std::fprintf(stderr, "INVOKE 第 %d 次失败\n", r + 1);
      return;
    }
    ms.push_back((t1.tv_sec - t0.tv_sec) * 1e3
                 + (t1.tv_nsec - t0.tv_nsec) / 1e6);
  }
  std::sort(ms.begin(), ms.end());
  double sum = 0.0;
  for (double v : ms) sum += v;

  /* 输出校验：哈希 + 极值 + 均值，便于跨组比对 */
  const TfLiteTensor* out = interpreter->tensor(outs[0]);
  std::uint64_t h = 1469598103934665603ULL;   /* FNV-1a 64 初值 */
  int omin = 127, omax = -128;
  long long osum = 0;
  std::size_t out_bytes = 0;
  if (out != nullptr && out->data.raw != nullptr && out->bytes > 0) {
    out_bytes = out->bytes;
    const std::int8_t* q = static_cast<const std::int8_t*>(out->data.raw);
    for (std::size_t k = 0; k < out_bytes; k++) {
      h ^= static_cast<std::uint8_t>(q[k]);
      h *= 1099511628211ULL;
      if (q[k] < omin) omin = q[k];
      if (q[k] > omax) omax = q[k];
      osum += q[k];
    }
  }
  std::fprintf(stderr,
               "INVOKE n=%d warmup=%d min_ms=%.3f median_ms=%.3f mean_ms=%.3f "
               "out_bytes=%zu out_hash=0x%016llx out_min=%d out_max=%d out_mean=%.4f\n",
               invoke_n, warmup, ms.front(), ms[ms.size() / 2],
               sum / static_cast<double>(ms.size()), out_bytes,
               static_cast<unsigned long long>(h), omin, omax,
               out_bytes ? static_cast<double>(osum) / static_cast<double>(out_bytes)
                         : 0.0);
}

static void print_shape(const TfLiteTensor* t) {
  std::fprintf(stderr, "[");
  for (int d = 0; d < t->dims->size; d++) {
    std::fprintf(stderr, "%s%d", d ? "," : "", t->dims->data[d]);
  }
  std::fprintf(stderr, "]");
}

int main(int argc, char** argv) {
  if (argc < 2) {
    std::fprintf(stderr,
                 "用法: %s <model.tflite> [libteflon.so] [--no-delegate] [--dump-tensors] [--invoke N]\n"
                 "  --no-delegate   不挂 delegate，用于归因（也用于取 CPU 基准耗时）\n"
                 "  --dump-tensors  逐张量转储 type/dims/量化参数/name\n"
                 "  --invoke N      真实推理 N 次并计时（含 3 次预热）；\n"
                 "                  输入用确定性模式填充，输出打 FNV-1a 哈希，\n"
                 "                  所以「挂 delegate」与「--no-delegate」两组的\n"
                 "                  耗时与 out_hash 可以直接对比\n",
                 argv[0]);
    return 64;
  }

  /* 解析 --no-delegate */
  bool no_delegate = false;
  bool dump_tensors = false;
  int  invoke_n = 0;          /* --invoke N：真实推理 N 次并计时 */
  const char* lib_path = nullptr;
  for (int i = 2; i < argc; i++) {
    if (std::strcmp(argv[i], "--no-delegate") == 0) {
      no_delegate = true;
    } else if (std::strcmp(argv[i], "--dump-tensors") == 0) {
      dump_tensors = true;
    } else if (std::strcmp(argv[i], "--invoke") == 0 && i + 1 < argc) {
      invoke_n = std::atoi(argv[++i]);
      if (invoke_n < 1) invoke_n = 1;
      if (invoke_n > 10000) invoke_n = 10000;
    } else {
      lib_path = argv[i];
    }
  }
  if (lib_path == nullptr) lib_path = "./libteflon.so";

  /* 输出必须无缓冲 —— 否则段错误时缓冲区里的 delegate 日志全部丢失，
   * 表现为「零输出」，会被误读成「崩在第一条日志之前」。
   * 真机上曾因此误判过（Mesa 的 teflon_debug 走 dump_graph，在最后才调用）。 */
  setvbuf(stdout, NULL, _IONBF, 0);
  setvbuf(stderr, NULL, _IONBF, 0);

  /* 段错误时打印调用栈。DSM 上没有 gdb，这是唯一的定位手段。
   * 地址可配合 nm / addr2line 在本地解析出函数名。 */
  install_crash_handler();

  std::fprintf(stderr, "=== tf_load_check ===\n");
  std::fprintf(stderr, "模型        : %s\n", argv[1]);
  std::fprintf(stderr, "TEFLON_DEBUG: %s\n",
               getenv("TEFLON_DEBUG") ? getenv("TEFLON_DEBUG") : "(未设置)");
  std::fprintf(stderr, "delegate    : %s\n",
               no_delegate ? "禁用（--no-delegate）" : lib_path);

  /* 1. 加载模型 —— tflite::FlatBufferModel，不是 TfLiteModel */
  std::unique_ptr<tflite::FlatBufferModel> model =
      tflite::FlatBufferModel::VerifyAndBuildFromFile(argv[1]);
  if (model == nullptr) {
    std::fprintf(stderr, "结果: FAIL - 模型加载/校验失败\n");
    return 1;
  }
  std::fprintf(stderr, "[1/4] 模型        : flatbuffer 解析并校验成功\n");
  std::fflush(stderr);

  /* 2. 加载 delegate
   *
   *    2.13 的 InterpreterBuilder::AddDelegate 只收实例、不收函数指针，
   *    且**不接管所有权**（头文件原文：
   *      "The lifetime of the delegate must be at least as long as the
   *       lifetime of any Interpreter generated by this InterpreterBuilder."）
   *    所以：自己 create → 挂到 builder → 保持到解释器销毁之后 → 自己 destroy。
   *
   *    库路径默认 ./libteflon.so，可用第 2 个命令行参数覆盖。 */
  TfLiteDelegate* delegate = nullptr;
  if (!no_delegate) {
    g_handle = dlopen(lib_path, RTLD_NOW | RTLD_LOCAL);
    if (g_handle == nullptr) {
      std::fprintf(stderr, "结果: FAIL - dlopen %s 失败: %s\n",
                   lib_path, dlerror());
      return 3;
    }
    std::fprintf(stderr, "[2/4] delegate 库  : %s 已加载\n", lib_path);

    DelegateCreateFn create_delegate = reinterpret_cast<DelegateCreateFn>(
        dlsym(g_handle, "tflite_plugin_create_delegate"));
    g_destroy = reinterpret_cast<DelegateDestroyFn>(
        dlsym(g_handle, "tflite_plugin_destroy_delegate"));
    if (create_delegate == nullptr || g_destroy == nullptr) {
      std::fprintf(stderr, "结果: FAIL - dlsym 失败: %s\n", dlerror());
      dlclose(g_handle);
      return 3;
    }

    delegate = create_delegate(nullptr);
    if (delegate == nullptr) {
      std::fprintf(stderr, "结果: FAIL - tflite_plugin_create_delegate 返回 NULL\n");
      dlclose(g_handle);
      return 3;
    }
    std::fprintf(stderr, "[2/4] delegate 符号: create=%p destroy=%p，实例已创建\n",
                 (void*)create_delegate, (void*)g_destroy);
    std::fflush(stderr);
  }

  /* 3. 构造解释器 —— 必须走 InterpreterBuilder
   *
   * ⚠️ 2.13 里 **AddDelegate 与 SetNumThreads 都是 InterpreterBuilder 的成员**，
   *    不是 InterpreterOptions 的。选项对象只有一个，挂在 builder 上即可，
   *    不必再单独构造 InterpreterOptions。 */
  tflite::ops::builtin::BuiltinOpResolver resolver;
  tflite::InterpreterBuilder builder(*model, resolver);
  if (delegate != nullptr) builder.AddDelegate(delegate);
  builder.SetNumThreads(1);
  std::fprintf(stderr, "[3/4] 即将构造解释器 InterpreterBuilder::operator() ...\n");
  std::fflush(stderr);
  std::unique_ptr<tflite::Interpreter> interpreter;
  if (builder(&interpreter) != kTfLiteOk || !interpreter) {
    std::fprintf(stderr, "结果: FAIL - 解释器创建失败\n");
    if (delegate) { g_destroy(delegate); dlclose(g_handle); }
    return 3;
  }
  std::fprintf(stderr, "[3/4] 解释器创建成功\n");
  std::fflush(stderr);

  /* 4. AllocateTensors —— 触发 PrepareDelegate，分区在这一步完成 */
  std::fprintf(stderr, "[4/4] 即将 AllocateTensors（会触发 PrepareDelegate）...\n");
  std::fflush(stderr);
  if (interpreter->AllocateTensors() != kTfLiteOk) {
    std::fprintf(stderr, "结果: FAIL - AllocateTensors 失败\n");
    interpreter.reset();
    if (delegate) { g_destroy(delegate); dlclose(g_handle); }
    return 2;
  }
  std::fprintf(stderr, "[4/4] AllocateTensors OK（delegate 分区已完成）\n");
  std::fflush(stderr);

  /* 5. 分区数 —— 接管是否发生的直接证据
   *    AllocateTensors 之后：
   *      1  → 只有主图，delegate 一个节点都没接管
   *      >1 → delegate 切出了分区
   *    （2.13 的 C API 没有 TfLiteInterpreterExecutionPlanSize，
   *      TfLiteInterpreterGetTensorCount 也不存在，必须用 C++ 接口。）*/
  const int n_partitions =
      static_cast<int>(interpreter->execution_plan().size());

  /* 6. dtype 统计 —— 判「真 int8 vs 假 int8」的关键指标 */
  const int n_tensors = static_cast<int>(interpreter->tensors_size());
  int n_int8 = 0, n_uint8 = 0, n_int32 = 0, n_float32 = 0, n_other = 0;
  int n_quantized = 0;   /* 带有效 scale 的量化张量 */
  int n_degenerate = 0;  /* scale 异常大，退化标量传染的征兆 */

  for (int i = 0; i < n_tensors; i++) {
    const TfLiteTensor* t = interpreter->tensor(i);
    if (t == nullptr) continue;
    switch (t->type) {
      case kTfLiteInt8:    n_int8++;    break;
      case kTfLiteUInt8:   n_uint8++;   break;
      case kTfLiteInt32:   n_int32++;   break;
      case kTfLiteFloat32: n_float32++; break;
      default:             n_other++;   break;
    }
    if ((t->type == kTfLiteInt8 || t->type == kTfLiteUInt8) &&
        t->params.scale > 0.0f) {
      n_quantized++;
      /* 正常 scale 在 1e-3 ~ 1e1 量级；
         1e10 以上说明是常量 0 张量导致的 0/0 退化传染。 */
      if (t->params.scale > 1.0e10f) n_degenerate++;
    }

    /* 逐张量转储：用来回答两个问题
     *   (1) tensors_size() 报出的槽位里有没有「未写入的占位槽」；
     *   (2) delegate 的 create_resource() 对未支持 dtype 会走
     *       default: unreachable("Unsupported TF type")，
     *       若被 NDEBUG 编译掉则 bytes 未初始化 → 必须列出所有非 INT8/INT32 的。
     * 每行：idx type dims has_data scale zp name
     * 有量化参数的标 *，无量化参数标 -（delegate 会跳过，见 fill_tensor 守卫）。 */
    if (dump_tensors) {
      const bool has_q = (t->quantization.type == kTfLiteAffineQuantization);
      char dims[96] = "?";
      if (t->dims != nullptr) {
        std::size_t off = 0;
        dims[0] = '\0';
        for (int d = 0; d < t->dims->size; d++) {
          int k = std::snprintf(dims + off, sizeof(dims) - off, "%s%d",
                                d ? "x" : "", t->dims->data[d]);
          if (k < 0 || static_cast<std::size_t>(k) >= sizeof(dims) - off) break;
          off += static_cast<std::size_t>(k);
        }
      }
      std::fprintf(stderr, "TENSOR %4d %-9s %-22s data=%-3s %c scale=%-14g zp=%-5d %s\n",
                   i, dtype_name(t->type), dims,
                   t->data.data ? "yes" : "no",
                   has_q ? '*' : '-',
                   t->params.scale,
                   static_cast<int>(t->params.zero_point),
                   (t->name != nullptr) ? t->name : "");
    }
  }
  if (dump_tensors) {
    std::fprintf(stderr, "TENSOR_DUMP_END count=%d\n", n_tensors);
  }

  /* 7. 输入/输出张量 —— Interpreter::inputs()/outputs() 返回 const std::vector<int>&
   *    （头文件里 `return tensor(inputs()[index])` 佐证其可索引） */
  {
    const std::vector<int>& ins = interpreter->inputs();
    const std::vector<int>& outs = interpreter->outputs();
    std::fprintf(stderr, "输入张量数    : %d\n", static_cast<int>(ins.size()));
    for (size_t i = 0; i < ins.size(); i++) {
      const TfLiteTensor* t = interpreter->tensor(ins[i]);
      if (t == nullptr) continue;
      std::fprintf(stderr, "  输入[%d] dtype=%s scale=%g zp=%lld shape=",
                   static_cast<int>(i), dtype_name(t->type), t->params.scale,
                   (long long)t->params.zero_point);
      print_shape(t);
      std::fprintf(stderr, "\n");
    }
    std::fprintf(stderr, "输出张量数    : %d\n", static_cast<int>(outs.size()));
    for (size_t i = 0; i < outs.size(); i++) {
      const TfLiteTensor* t = interpreter->tensor(outs[i]);
      if (t == nullptr) continue;
      std::fprintf(stderr, "  输出[%d] dtype=%s scale=%g zp=%lld shape=",
                   static_cast<int>(i), dtype_name(t->type), t->params.scale,
                   (long long)t->params.zero_point);
      print_shape(t);
      std::fprintf(stderr, "\n");
    }
  }

  /* 7b. Invoke：真实推理 + 计时 + 输出校验
   *
   * 为什么必须有这一段：`AllocateTensors()` 只证明 delegate 完成了分区，
   * **不证明推理能跑、更不证明它更快**。而当前被接管的只有 CONCAT/PAD
   * （卷积因 per-channel 量化留在 CPU），所以「NPU 版是否更快」无法先验判断，
   * 只能实测。
   *
   * 输入用**确定性模式**填充，保证 CPU 组与 NPU 组喂的是同一份数据；
   * 输出打 FNV-1a 哈希 —— 两边哈希相同即说明计算结果一致。
   */
  if (invoke_n > 0) {
    run_invoke(interpreter.get(), invoke_n);
  }

  /* 8. 机器可读摘要：一行 key=value，便于 grep/awk 判定 */
  std::fprintf(stderr,
               "SUMMARY partitions=%d tensors=%d int8=%d uint8=%d int32=%d "
               "float32=%d other=%d quantized_tensors=%d degenerate_scales=%d\n",
               n_partitions, n_tensors, n_int8, n_uint8, n_int32,
               n_float32, n_other, n_quantized, n_degenerate);

  if (n_degenerate > 0) {
    std::fprintf(stderr,
                 "警告: %d 个张量的 scale > 1e10 —— 疑似 0/0 退化传染\n",
                 n_degenerate);
  }

  /* 分区数 > 1 才说明 delegate 真的切出了分区。
   *
   * 注意：partitions == 1 **不一定**是 bug。
   * teflon 对每个节点独立判定（PrepareDelegate 里 if (supported) 才入委托），
   * 若一个节点都不支持，就不会产生分区。
   * 要与 TEFLON_DEBUG=2 的逐节点日志一起看 —— 空日志无法区分这两种情况，
   * 而设错 TEFLON_DEBUG 的值（=1）恰好就会得到空日志。 */
  const char* verdict = (n_partitions > 1) ? "DELEGATE_ACTIVE"
                                           : "DELEGATE_NO_PARTITION";
  std::fprintf(stderr, "结果: OK - %s (partitions=%d)\n", verdict, n_partitions);

  /* 顺序重要：delegate 的生命周期必须长于 interpreter */
  interpreter.reset();
  if (delegate) {
    g_destroy(delegate);
    dlclose(g_handle);
  }
  return 0;
}