/* tf_load_check.cpp —— 上机验证 Teflon delegate 能否接管 .tflite 模型的节点
 *
 * ## 为什么需要这个程序
 *
 * 我们之前只验证过「delegate 能加载」：
 *   teflon_dlopen → dlopen libteflon.so → 找到 tflite_plugin_create_delegate
 *   → 调用它 → 返回非 NULL
 * 那只能证明 **库能加载、符号能解析、设备能被枚举**。
 *
 * Mesa tfl_device.c 的 tflite_plugin_create_delegate()（L1687-1712）只做两件事：
 *   delegate->dev  = find_accel_device() / find_drm_device()
 *   delegate->base.Prepare = PrepareDelegate
 * 它**从不调用 PrepareDelegate**。
 *
 * PrepareDelegate 真正被回调是在 TFLite 解释器 AllocateTensors() 期间
 * （ReplaceNodeSubsetsWithDelegateKernels 那一步）。
 * 所以「能加载」与「能接管节点」是两件事，必须用解释器验证。
 *
 * ## 本程序做什么 / 不做什么
 *
 * 做：
 *   1. 加载 .tflite 模型
 *   2. 建解释器，把 libteflon.so 的 external delegate 挂上去
 *   3. AllocateTensors()   ← 这一步触发 PrepareDelegate
 *   4. 打印张量统计与**分区数**
 *
 * 不做：不做前处理/反量化、不要求推理结果正确、不 Invoke()。
 * 因为接管分区在 AllocateTensors 阶段就已完成，
 * 数值正确与否与「哪些节点被接管」是两件独立的事。
 *
 * ## 关键环境变量
 *
 *   TEFLON_DEBUG=2   打开 delegate 的逐节点日志（注意是 2 不是 1）
 *
 *   源码 tfl_device.c L31  TEFLON_DEBUG_VERBOSE = 1 << 1   → 值是 2
 *   源码 tfl_device.c L43  teflon_debug() 整个函数体被
 *                               & TEFLON_DEBUG_VERBOSE 门控
 *   设成 1 只置 bit0，1 & 2 == 0 → 一行日志都不打。
 *   而空日志极易被误读成「delegate 没接管任何节点」—— 方向正好反了。
 *
 * ## TFLite 2.13.0 的 API 用法（逐条对过头文件，不是凭印象）
 *
 * ⚠️ 2.13 与直觉差别很大，这里列出来免得后面再踩：
 *
 *  1. 类名是 **tflite::Interpreter**，不是 tflite::TfLiteInterpreter。
 *     来源：tensorflow/lite/core/interpreter.h
 *
 *  2. 构造解释器要用 **InterpreterBuilder**，不能直接 new：
 *     InterpreterBuilder(const FlatBufferModel&, const OpResolver&,
 *                        const InterpreterOptions* = nullptr);
 *     TfLiteStatus operator()(std::unique_ptr<Interpreter>*);
 *     来源：tensorflow/lite/core/interpreter_builder.h
 *
 *  3. AddDelegate **只收实例，不收函数指针**（旧式三参数版在 2.13 已移除）：
 *     void AddDelegate(TfLiteDelegate* delegate);
 *     且**不接管所有权** —— 头文件原文：
 *       "The lifetime of the delegate must be at least as long as the
 *        lifetime of any Interpreter generated by this InterpreterBuilder."
 *     所以自己 create、自己保持存活、自己 destroy。
 *
 *  4. **C API 走不通**：2.13 的
 *     TfLiteInterpreterOptionsAddDelegate(TfLiteInterpreterOptions*,
 *                                         TfLiteOpaqueDelegate*)
 *     要的是 TfLiteOpaqueDelegate 实例（无头文件名里的
 *     `TfLiteOpaqueDelegate* (*)(const char* data, const char* options)` 形式），
 *     与 Mesa teflon 导出的旧式 TfLiteDelegate*(*)(const char*) 不同型。
 *     → 旧式 delegate 只能走 C++ API。
 *
 *  5. C API 里 TfLiteInterpreterExecutionPlanSize / GetTensorCount 在 2.13
 *     **不存在**（实测 tensorflow/lite/core/c/c_api.h 无这两个符号）。
 *     分区数改用 C++ 的 Interpreter::execution_plan()。
 *
 *  6. 模型类是 **tflite::FlatBufferModel**（core/model_builder.h，
 *     实为 `using FlatBufferModel = impl::FlatBufferModel`），
 *     且**没有默认构造函数**（拷贝构造被 delete），
 *     必须用静态工厂 VerifyAndBuildFromFile() / BuildFromFile()。
 *
 *  7. ⚠️ **AddDelegate 与 SetNumThreads 是 InterpreterBuilder 的成员，
 *     不是 InterpreterOptions 的**：
 *         class InterpreterBuilder {
 *           InterpreterBuilder(const FlatBufferModel&, const OpResolver&,
 *                              const InterpreterOptions* = nullptr);
 *           void AddDelegate(TfLiteDelegate* delegate);
 *           TfLiteStatus SetNumThreads(int);
 *           TfLiteStatus operator()(std::unique_ptr<Interpreter>*);
 *         };
 *     没有必要单独构造 InterpreterOptions 对象。
 *
 *  8. Interpreter **没有 subgraph_count()**，别写。
 *
 *  9. lite/ 下的 model.h / interpreter.h 都是**转发 stub**，
 *     真正有内容的是 lite/core/ 下的同名文件。
 *
 * ## 退出码
 *
 *   0   成功
 *   64  用法错误
 *   1   模型加载失败
 *   3   解释器创建失败
 *   2   AllocateTensors 失败
 */

#include <cstdio>
#include <cstdlib>
#include <memory>
#include <vector>

#include "tensorflow/lite/core/model_builder.h"       // FlatBufferModel
#include "tensorflow/lite/core/interpreter_builder.h" // InterpreterBuilder
#include "tensorflow/lite/core/interpreter.h"         // Interpreter
#include "tensorflow/lite/kernels/register.h"         // BuiltinOpResolver
#include "tensorflow/lite/c/c_api_types.h"

/* libteflon.so 导出的 external delegate 入口（Mesa teflon，旧式 C ABI） */
extern "C" TfLiteDelegate* tflite_plugin_create_delegate(const char*);
extern "C" void tflite_plugin_destroy_delegate(TfLiteDelegate*);

/* teflon 内部的 tflite_type_name 是 file-static 短名版本（L1370），
 * 与公开枚举名不同。这里用公开枚举打印，便于阅读。 */
static const char* dtype_name(TfLiteType t) {
  switch (t) {
    case kTfLiteFloat32: return "FLOAT32";
    case kTfLiteInt32:   return "INT32";
    case kTfLiteUInt8:   return "UINT8";
    case kTfLiteInt64:   return "INT64";
    case kTfLiteString:  return "STRING";
    case kTfLiteBool:    return "BOOL";
    case kTfLiteInt16:   return "INT16";
    case kTfLiteComplex64:  return "COMPLEX64";
    case kTfLiteInt8:    return "INT8";
    case kTfLiteFloat16: return "FLOAT16";
    case kTfLiteFloat64: return "FLOAT64";
    default:             return "OTHER";
  }
}

static void print_shape(const TfLiteTensor* t) {
  std::fprintf(stderr, "[");
  for (int d = 0; d < t->dims->size; d++) {
    std::fprintf(stderr, "%s%d", d ? "," : "", t->dims->data[d]);
  }
  std::fprintf(stderr, "]");
}

int main(int argc, char** argv) {
  if (argc < 2) {
    std::fprintf(stderr, "用法: %s <model.tflite>\n", argv[0]);
    return 64;
  }

  std::fprintf(stderr, "=== tf_load_check ===\n");
  std::fprintf(stderr, "模型        : %s\n", argv[1]);
  std::fprintf(stderr, "TEFLON_DEBUG: %s\n",
               getenv("TEFLON_DEBUG") ? getenv("TEFLON_DEBUG") : "(未设置)");

  /* 1. 加载模型 —— tflite::FlatBufferModel，不是 TfLiteModel */
  std::unique_ptr<tflite::FlatBufferModel> model =
      tflite::FlatBufferModel::VerifyAndBuildFromFile(argv[1]);
  if (model == nullptr) {
    std::fprintf(stderr, "结果: FAIL - 模型加载/校验失败\n");
    return 1;
  }
  std::fprintf(stderr, "模型        : flatbuffer 解析并校验成功\n");

  /* 2. 挂 delegate
   *    2.13 的 AddDelegate 只收实例且不接管所有权，
   *    所以自己 create、保持到解释器销毁之后、自己 destroy。 */
  TfLiteDelegate* delegate = tflite_plugin_create_delegate(nullptr);
  if (delegate == nullptr) {
    std::fprintf(stderr, "结果: FAIL - tflite_plugin_create_delegate 返回 NULL\n");
    return 3;
  }
  std::fprintf(stderr, "delegate    : 已创建\n");

  /* 3. 构造解释器 —— 必须走 InterpreterBuilder
   *
   * ⚠️ 2.13 里 **AddDelegate 与 SetNumThreads 都是 InterpreterBuilder 的成员**，
   *    不是 InterpreterOptions 的。选项对象只有一个，挂在 builder 上即可，
   *    不必再单独构造 InterpreterOptions。 */
  tflite::ops::builtin::BuiltinOpResolver resolver;
  tflite::InterpreterBuilder builder(*model, resolver);
  builder.AddDelegate(delegate);
  builder.SetNumThreads(1);
  std::unique_ptr<tflite::Interpreter> interpreter;
  if (builder(&interpreter) != kTfLiteOk || !interpreter) {
    std::fprintf(stderr, "结果: FAIL - 解释器创建失败\n");
    tflite_plugin_destroy_delegate(delegate);
    return 3;
  }
  std::fprintf(stderr, "解释器      : 创建成功\n");

  /* 4. AllocateTensors —— 触发 PrepareDelegate，分区在这一步完成 */
  if (interpreter->AllocateTensors() != kTfLiteOk) {
    std::fprintf(stderr, "结果: FAIL - AllocateTensors 失败\n");
    interpreter.reset();
    tflite_plugin_destroy_delegate(delegate);
    return 2;
  }
  std::fprintf(stderr, "AllocateTensors: OK（delegate 分区已完成）\n");

  /* 5. 分区数 —— 接管是否发生的直接证据
   *    AllocateTensors 之后：
   *      1  → 只有主图，delegate 一个节点都没接管
   *      >1 → delegate 切出了分区
   *    （2.13 的 C API 没有 TfLiteInterpreterExecutionPlanSize，
   *      TfLiteInterpreterGetTensorCount 也不存在，必须用 C++ 接口。）*/
  const int n_partitions =
      static_cast<int>(interpreter->execution_plan().size());

  /* 6. dtype 统计 —— 判「真 int8 vs 假 int8」的关键指标 */
  const int n_tensors = static_cast<int>(interpreter->tensors_size());
  int n_int8 = 0, n_uint8 = 0, n_int32 = 0, n_float32 = 0, n_other = 0;
  int n_quantized = 0;   /* 带有效 scale 的量化张量 */
  int n_degenerate = 0;  /* scale 异常大，退化标量传染的征兆 */

  for (int i = 0; i < n_tensors; i++) {
    const TfLiteTensor* t = interpreter->tensor(i);
    if (t == nullptr) continue;
    switch (t->type) {
      case kTfLiteInt8:    n_int8++;    break;
      case kTfLiteUInt8:   n_uint8++;   break;
      case kTfLiteInt32:   n_int32++;   break;
      case kTfLiteFloat32: n_float32++; break;
      default:             n_other++;   break;
    }
    if ((t->type == kTfLiteInt8 || t->type == kTfLiteUInt8) &&
        t->params.scale > 0.0f) {
      n_quantized++;
      /* 正常 scale 在 1e-3 ~ 1e1 量级；
         1e10 以上说明是常量 0 张量导致的 0/0 退化传染。 */
      if (t->params.scale > 1.0e10f) n_degenerate++;
    }
  }

  /* 7. 输入/输出张量 —— Interpreter::inputs()/outputs() 返回 const std::vector<int>&
   *    （头文件里 `return tensor(inputs()[index])` 佐证其可索引） */
  {
    const std::vector<int>& ins = interpreter->inputs();
    const std::vector<int>& outs = interpreter->outputs();
    std::fprintf(stderr, "输入张量数    : %d\n", static_cast<int>(ins.size()));
    for (size_t i = 0; i < ins.size(); i++) {
      const TfLiteTensor* t = interpreter->tensor(ins[i]);
      if (t == nullptr) continue;
      std::fprintf(stderr, "  输入[%d] dtype=%s scale=%g zp=%lld shape=",
                   static_cast<int>(i), dtype_name(t->type), t->params.scale,
                   (long long)t->params.zero_point);
      print_shape(t);
      std::fprintf(stderr, "\n");
    }
    std::fprintf(stderr, "输出张量数    : %d\n", static_cast<int>(outs.size()));
    for (size_t i = 0; i < outs.size(); i++) {
      const TfLiteTensor* t = interpreter->tensor(outs[i]);
      if (t == nullptr) continue;
      std::fprintf(stderr, "  输出[%d] dtype=%s scale=%g zp=%lld shape=",
                   static_cast<int>(i), dtype_name(t->type), t->params.scale,
                   (long long)t->params.zero_point);
      print_shape(t);
      std::fprintf(stderr, "\n");
    }
  }

  /* 8. 机器可读摘要：一行 key=value，便于 grep/awk 判定 */
  std::fprintf(stderr,
               "SUMMARY partitions=%d tensors=%d int8=%d uint8=%d int32=%d "
               "float32=%d other=%d quantized_tensors=%d degenerate_scales=%d\n",
               n_partitions, n_tensors, n_int8, n_uint8, n_int32,
               n_float32, n_other, n_quantized, n_degenerate);

  if (n_degenerate > 0) {
    std::fprintf(stderr,
                 "警告: %d 个张量的 scale > 1e10 —— 疑似 0/0 退化传染\n",
                 n_degenerate);
  }

  /* 分区数 > 1 才说明 delegate 真的切出了分区。
   *
   * 注意：partitions == 1 **不一定**是 bug。
   * teflon 对每个节点独立判定（PrepareDelegate 里 if (supported) 才入委托），
   * 若一个节点都不支持，就不会产生分区。
   * 要与 TEFLON_DEBUG=2 的逐节点日志一起看 —— 空日志无法区分这两种情况，
   * 而设错 TEFLON_DEBUG 的值（=1）恰好就会得到空日志。 */
  const char* verdict = (n_partitions > 1) ? "DELEGATE_ACTIVE"
                                           : "DELEGATE_NO_PARTITION";
  std::fprintf(stderr, "结果: OK - %s (partitions=%d)\n", verdict, n_partitions);

  /* 顺序重要：delegate 的生命周期必须长于 interpreter */
  interpreter.reset();
  tflite_plugin_destroy_delegate(delegate);
  return 0;
}